"""Installs RomFS mods for totk-pc-recomp (any game version the recomp supports: 1.2.1, 1.4.3, ...).

Usage (from the game folder, next to totk.exe):
    1. Extract each mod into mods-sources\\<mod name>\\  (it must contain a romfs\\ folder)
    2. Run:  py install_mods.py   (or use TOTK Mod Manager.pyw)
    3. Start the game.

Rebuilds mods\\active\\ from every enabled mod in mods-sources (alphabetical order; a folder starting
with "_" or unchecked in the Mod Manager is skipped), writes the manifest.tsv the recomp requires, patches the game's
resource size table (from .rcl files or tables shipped with the mods) and updates the romfs_mods line of totk.ini.
Never modifies romfs.bin. Needs Python 3.14 (built-in zstd) or an older Python with "py -m pip install zstandard".
"""
import hashlib
import json
import re
import shutil
import struct
import sys
import zlib
from pathlib import Path

try:
    from compression import zstd as _z          # Python 3.14+
    unz = lambda b: _z.decompress(b)
    z = lambda b: _z.compress(b, level=16)
except ImportError:
    try:
        import zstandard as _zs
        unz = lambda b: _zs.ZstdDecompressor().decompress(b, max_output_size=256 << 20)
        z = lambda b: _zs.ZstdCompressor(level=16).compress(b)
    except ImportError:
        sys.exit('Python 3.14 is required, or install zstandard:  py -m pip install zstandard')

ROOT = Path(sys.executable if getattr(sys, 'frozen', False) else __file__).resolve().parent   # .exe build: its folder
SOURCES, OUT = ROOT / 'mods-sources', ROOT / 'mods' / 'active'
# The size table is named ...Product.143.Nin_NX_NVN.rsizetable.zs on 1.4.3 but ...Product.121.rsizetable.zs on 1.2.1:
# ".Nin_NX_NVN" is optional, and the System/Resource/ prefix is not required for detection.
RESTBL_RE = re.compile(rb'ResourceSizeTable\.Product\.(\d+)(?:\.Nin_NX_NVN)?\.rsizetable\.zs')


def game_version():
    """('143', '1.4.3') for the installed game, read from romfs-index.bin (fallback: totk-install.json);
    (None, 'unknown') if it cannot tell."""
    try:
        found = RESTBL_RE.findall((ROOT / 'romfs-index.bin').read_bytes())
    except OSError:
        found = []
    if found:
        v = max(found, key=int).decode()
        return v, '.'.join(v)
    try:                                 # written by the recomp setup: {"version": "1.2.1", ...}
        v = json.loads((ROOT / 'totk-install.json').read_text(encoding='utf-8'))['version']
        if re.fullmatch(r'\d\.\d\.\d', v):
            return v.replace('.', ''), v
    except (OSError, ValueError, KeyError, TypeError):
        pass
    return None, 'unknown'
MARK = '# generated by install_mods.py'
STATE = SOURCES / 'state.json'         # {"disabled": [folder names]}


def disabled():
    import json
    try:
        return set(json.loads(STATE.read_text(encoding='utf-8')).get('disabled', []))
    except (OSError, ValueError):
        return set()


def set_disabled(names):
    import json
    STATE.write_text(json.dumps({'disabled': sorted(names)}, ensure_ascii=False, indent=1), encoding='utf-8')


def all_mods():
    return sorted((d for d in SOURCES.iterdir() if d.is_dir() and not d.name.startswith('_')), key=lambda d: d.name.lower())


def load_index():
    try:
        b = (ROOT / 'romfs-index.bin').read_bytes()
    except OSError:
        raise RuntimeError(f'romfs-index.bin not found in {ROOT}: put the Mod Manager in the recomp install folder, '
                           'next to totk.exe.')
    magic, n, so = struct.unpack_from('<8sQQ', b)
    assert magic == b'TOTKRFS1', 'unexpected romfs-index.bin'
    idx = {}
    for i in range(n):
        off, size, no, ln = struct.unpack_from('<QQII', b, 24 + i * 24)
        idx[b[so + no:so + no + ln - 1].decode()] = (off, size)
    return idx


def restbl_load(zs):
    b = unz(zs)
    assert b[:6] == b'RESTBL', 'unreadable resource size table'
    ver, nl, nc, nn = struct.unpack_from('<IIII', b, 6)
    o = 22
    crc = dict(struct.unpack_from('<II', b, o + 8 * i) for i in range(nc))
    o += 8 * nc
    names = {}
    for i in range(nn):
        p = o + i * (nl + 4)
        names[b[p:p + nl].split(b'\0')[0].decode()] = struct.unpack_from('<I', b, p + nl)[0]
    return ver, nl, crc, names


def restbl_get(t, path):
    return t[3].get(path, t[2].get(zlib.crc32(path.encode())))


def restbl_set(t, path, size):
    if path in t[3]:
        t[3][path] = size
    else:
        t[2][zlib.crc32(path.encode())] = size


def restbl_dump(t):
    ver, nl, crc, names = t
    out = bytearray(b'RESTBL' + struct.pack('<IIII', ver, nl, len(crc), len(names)))
    for k in sorted(crc):
        out += struct.pack('<II', k, crc[k])
    for n in sorted(names):
        out += n.encode().ljust(nl, b'\0') + struct.pack('<I', names[n])
    return z(bytes(out))


def table_key(path):
    """Size table key: the path without .zs / .mc (compressed extensions)."""
    return re.sub(r'\.(zs|mc)$', '', path)


def install(mods):
    """Rebuilds mods/active from these folders (in this order, the last one wins). -> (warnings, summary)"""
    idx = load_index()
    code, ver = game_version()
    # real path of the size table in the index (its name differs between game versions)
    RESTBL = next((k for k in idx if code and re.fullmatch(
        rf'(?:.*/)?ResourceSizeTable\.Product\.{code}(?:\.Nin_NX_NVN)?\.rsizetable\.zs', k)), None)
    image = open(ROOT / 'romfs' / 'romfs.bin', 'rb')

    def original(path):
        off, size = idx[path]
        image.seek(off)
        return image.read(size)

    files, sizes, warn, skipped = {}, {}, [], {}      # RomFS path -> (source file, mod name); table key -> size
    for mod in mods:
        romfs = next((p for p in sorted(mod.rglob('romfs'), key=lambda p: len(p.parts)) if p.is_dir()), None)
        if not romfs:
            warn.append(f'{mod.name}: no romfs folder, skipped')
            continue
        if any(mod.rglob('exefs')):
            warn.append(f'{mod.name}: has an exefs folder, which the recomp does not load (only romfs is installed)')
        excl = [l.strip() for x in mod.rglob('exclude.txt') for l in x.read_text(encoding='utf-8').splitlines()
                if l.strip() and not l.startswith('#')]   # romfs path prefixes this mod must not install
        for f in sorted(romfs.rglob('*')):
            if not f.is_file():
                continue
            p = f.relative_to(romfs).as_posix()
            if any(p.startswith(x) for x in excl):
                continue
            if p.startswith('System/Resource/ResourceSizeTable'):
                try:                     # table for another version: keep only the sizes of this mod's files
                    t = restbl_load(f.read_bytes())
                    for q in romfs.rglob('*'):
                        k = table_key(q.relative_to(romfs).as_posix())
                        v = restbl_get(t, k) if q.is_file() else None
                        if v:
                            sizes[k] = max(sizes.get(k, 0), v)
                except Exception as e:
                    warn.append(f'{mod.name}: unreadable table {f.name} ({e})')
                continue
            if p not in idx and re.search(r'\.Product\.\d+\.', p):
                skipped.setdefault(mod.name, []).append(p)   # file for another game version: this game never reads it
                continue
            if f.suffix.lower() in ('.exe', '.dll', '.bat', '.txt', '.md'):
                continue
            if p in files and files[p][0].read_bytes() == f.read_bytes():
                continue                 # same file shipped by two mods (shared merged copy): not a conflict
            if p in files:
                warn.append(f'{p}: in both {files[p][1]} and {mod.name}, using {mod.name}')
            files[p] = (f, mod.name)
        for rcl in mod.rglob('*.rcl'):
            for line in rcl.read_text(encoding='utf-8', errors='replace').splitlines():
                m = re.match(r'\s*\*\s*(.+?)\s*=\s*(\d+)', line)
                if m:
                    sizes[m[1]] = max(sizes.get(m[1], 0), int(m[2]))

    if sizes and RESTBL is None:         # stop before touching mods/active: a mod installed without it can crash the game
        image.close()
        raise RuntimeError(f'Game version {ver}: resource size table not found in romfs-index.bin, so the mods '
                           'cannot be installed safely. Nothing was installed.')

    for name, paths in skipped.items():
        if any(src[1] == name and re.search(r'\.Product\.\d+\.', q) for q, src in files.items()):
            continue                     # multi-version mod: it also ships this version's files
        warn.append(f'{name}: made for another game version ({len(paths)} file(s) like {paths[0].rsplit("/", 1)[-1]} '
                    f'were skipped). It may not work or may crash on {ver}: look for a {ver} version of this mod.')
    if OUT.exists():
        if not (OUT / 'manifest.tsv').is_file() or '# generated by install' not in (OUT / 'manifest.tsv').read_text(encoding='utf-8'):
            raise RuntimeError(f'{OUT} exists and was not created by this script: rename or delete it.')
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    sha = lambda b: hashlib.sha256(b).hexdigest()
    lines = []

    def put(path, data, orig):
        dst = OUT / path
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(data)
        lines.append(f'{path}\t{len(data)}\t{sha(data)}\t{orig}')

    for p, (f, _) in sorted(files.items()):
        put(p, f.read_bytes(), sha(original(p)) if p in idx else '-')
    if sizes:
        orig = original(RESTBL)
        t = restbl_load(orig)
        for k, v in sizes.items():
            restbl_set(t, k, max(v, restbl_get(t, k) or 0))
        put(RESTBL, restbl_dump(t), sha(orig))

    (OUT / 'manifest.tsv').write_text(MARK + '\n' + '\n'.join(sorted(lines)) + '\n', encoding='utf-8', newline='\n')

    ini = ROOT / 'totk.ini'
    text = ini.read_text(encoding='utf-8')
    want = f'romfs_mods = {OUT}' if lines else '# romfs_mods ='
    text = re.sub(r'(?m)^#?[ \t]*romfs_mods[ \t]*=.*\n?', '', text)
    if '[files]' in text:
        text = text.replace('[files]\n', f'[files]\n{want}\n', 1)
    else:
        text += f'\n[files]\n{want}\n'
    ini.write_text(text, encoding='utf-8', newline='')

    image.close()
    summary = (f'{len(mods)} mod(s), {len(files)} file(s), size table {"patched" if sizes else "unchanged"}. '
               + ('Start the game.' if lines else 'No active mods: romfs_mods disabled.'))
    return warn, summary


def main():
    if not SOURCES.is_dir():
        SOURCES.mkdir()
        sys.exit(f'Created {SOURCES}\nExtract your mods into it (one folder per mod), then run again.')
    off = disabled()
    warn, summary = install([m for m in all_mods() if m.name not in off])
    for w in warn:
        print('warning:', w)
    print(summary)


if __name__ == '__main__':
    main()
